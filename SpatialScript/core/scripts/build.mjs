// Builds core/dist/spatial-core.js: a single IIFE that runs unchanged in
// JavaScriptCore and in a browser.

import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

await build({
  entryPoints: [path.join(root, "src/index.js")],
  outfile: path.join(root, "dist/spatial-core.js"),
  bundle: true,
  format: "iife",
  target: "es2022",
  platform: "neutral",
  minify: false,
  sourcemap: false,
  legalComments: "none",
  loader: { ".json": "json" },
  banner: {
    js: "// SpatialScript core bundle. Generated by core/scripts/build.mjs -- do not edit by hand.",
  },
  logLevel: "info",
});
