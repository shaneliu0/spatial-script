// Builds core/dist/spatial-core.js: a single IIFE that runs unchanged in
// JavaScriptCore and in a browser.

import { build } from "esbuild";
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

await build({
  entryPoints: [path.join(root, "src/index.js")],
  outfile: path.join(root, "dist/spatial-core.js"),
  bundle: true,
  format: "iife",
  target: "es2022",
  platform: "neutral",
  minify: false,
  sourcemap: false,
  legalComments: "none",
  loader: { ".json": "json" },
  // three.js registers itself with the browser devtools extension behind a
  // `typeof window !== "undefined"` guard. That guard is the one place the
  // bundle reads a browser global while the IIFE body runs, and SPEC 12 says
  // it must not: substituting `undefined` lets esbuild fold the block away.
  define: { window: "undefined" },
  banner: {
    js: "// SpatialScript core bundle. Generated by core/scripts/build.mjs -- do not edit by hand.",
  },
  logLevel: "info",
});

// The RealityKit consumer bundles a copy of the same file as a SwiftPM resource
// (Package.swift `resources`). Copying it here keeps the two from drifting: a
// core change reaches the app on the next build without a manual step.
const swiftCopy = path.resolve(
  root,
  "../../Packages/RealityKitScripting/Sources/RealityKitScripting/Resources/spatial-core.js",
);
if (fs.existsSync(path.dirname(swiftCopy))) {
  fs.copyFileSync(path.join(root, "dist/spatial-core.js"), swiftCopy);
  console.log("copied the bundle to the RealityKit package resources");
}
